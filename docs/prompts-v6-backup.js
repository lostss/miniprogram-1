// stripToolCardMarkers：清理流式文本中可能残留的 [TOOL]/[CARD]/[INTENT] 标记
// 注：sug 模式已下线 [CARD] 语法，但保留清理逻辑作为兜底（AI 可能误模仿旧语法）
function stripToolCardMarkers(text) {
  if (!text) return ''
  return text
    .replace(/\[TOOL:\w+\][\s\S]*?\[\/TOOL\]/g, '')
    .replace(/\[CARD:\w+\][\s\S]*?\[\/CARD\]/g, '')
    .replace(/\[TOOL:\w+\]/g, '')
    .replace(/\[\/TOOL\]/g, '')
    .replace(/\[INTENT(?::\w+)?\]/g, '')
}

