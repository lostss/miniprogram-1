// 机构后缀词（按长度降序迭代剥离；剥离后仍可能残留品牌内合法词，故只剥纯机构后缀）
const SUFFIXES = ['集团股份有限公司', '股份有限公司', '有限责任公司', '有限公司', '股份公司', '集团公司', '保险公司', '保险集团', '保险股份', '保险有限', '保险责任', '集团', '保险']

function _fallback(raw) {
  let s = raw
  for (let round = 0; round < 3; round++) {
    let hit = false
    for (let i = 0; i < SUFFIXES.length; i++) {
      const suf = SUFFIXES[i]
      if (s.length > suf.length && s.endsWith(suf)) {
        s = s.slice(0, s.length - suf.length)
        hit = true
        break
      }
    }
    if (!hit) break
  }
  // 剥离后只剩泛词/过短 → 原样返回，不做危险猜测
  if (s.length < 2 || /^(人寿|养老|健康|保险|集团|中国|中)$/.test(s)) return raw
  return s
}

/**
 * 归一保险公司名为统一简称（幂等：简称输入返回同值）
 * @param {*} input
 * @returns {string}
 */
function normalizeInsurer(input) {
  const raw = String(input || '').trim().replace(/\s+/g, '')
  if (!raw) return ''
  if (LIFE_MAP[raw]) return LIFE_MAP[raw]
  // contains 匹配：长 key 优先（防短 key 误命中，如"太平人寿"与"中国太平"）
  let best = null
  const keys = Object.keys(LIFE_MAP)
  for (let i = 0; i < keys.length; i++) {
    const k = keys[i]
    if (k.length >= 2 && raw.indexOf(k) !== -1 && (!best || k.length > best.length)) best = k
  }
  if (best) return LIFE_MAP[best]
  return _fallback(raw)
}

module.exports = { normalizeInsurer, LIFE_MAP }
