- 「年收入」：家庭总收入，取自经济状况表。禁止用各成员个人年收入累加，禁止将家庭年收入分摊到成员个人
- 「角色」：已由数据层归一化，可能值为：经济支柱、配偶、子女、父母、其他。作为成员身份标签直接使用，不得修改。在判断家庭整体结构（单支柱/双支柱/有无赡养责任）时，可综合角色+收入+年龄等多字段做出准确描述，而非仅依赖角色标签做单一判断
