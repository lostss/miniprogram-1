// ======================== 标记清理（兜底，防旧协议残留） ========================
function stripToolCardMarkers(text) {
  if (!text) return ''
  return text
    .replace(/\[TOOL:\w+\][\s\S]*?\[\/TOOL\]/g, '')
    .replace(/\[CARD:\w+\][\s\S]*?\[\/CARD\]/g, '')
    .replace(/\[TOOL:\w+\]/g, '')
    .replace(/\[\/TOOL\]/g, '')
    .replace(/\[INTENT(?::\w+)?\]/g, '')
    .replace(/\{TOOL_INTENT:[\s\S]*?\}\s*/g, '')
}

